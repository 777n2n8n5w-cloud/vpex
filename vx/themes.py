# Identity recipes for every public theme. Each line is one theme's light, material and motion:
#   L    up to three ambient lights as (hex, strength 0-1). Strength is the peak when you're on a roll;
#        at rest the room sits at about two thirds of it, and it warms with each call.
#   P    optional positions for the lights, "x% y%" each (defaults: low left, right side, below).
#   tx   texture from vx/build.py TEX (none when the theme already has its own pattern).
#   txo  texture strength.     g   grain.     vig  vignette.     amb  overall light (0 = no lights).
#   mo   motion personality: silk, glide, snap, bounce, float, step, hard, still.
#   det  card detail: hair (inner hairline), stitch (seam), corners (brackets), foil (sweep on deal-in).
#   f    foil colors (two hex), defaults to the accent and the second light.

