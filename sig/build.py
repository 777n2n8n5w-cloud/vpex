#!/usr/bin/env python3
"""Builds sig.css (repo root) from sig/base.css and the five theme files.

Theme files use three placeholders so every rule stays scoped to its own theme:
  @V  the token block: the live theme and its preview tiles (.sig-scope[data-sig=...])
  @T  the live theme:  html.sig.sig[data-theme="sig-x"]  (0,3,1), above the shared theme rules
  @M  the live theme with motion on (decorative animation only; also wrapped in prefers-reduced-motion)
Run: python3 sig/build.py   (tests/signature_themes.js checks sig.css is up to date)
"""
import re, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
ORDER = ["horologe", "urushi", "premiere", "blueprint", "prism"]
PH = re.compile(r"@([VTM])(?=[\s\[.:#,{(])")


def expand(src, tid):
    sel = {
        "V": 'html.sig.sig[data-theme="%s"], .sig-scope[data-sig="%s"]' % (tid, tid),
        "T": 'html.sig.sig[data-theme="%s"]' % tid,
        "M": 'html.sig.sig[data-motion="on"][data-theme="%s"]' % tid,
    }
    return PH.sub(lambda m: sel[m.group(1)], src)


def build():
    out = [(HERE / "base.css").read_text()]
    for name in ORDER:
        src = (HERE / (name + ".css")).read_text()
        m = re.match(r"/\*! id: (sig-[a-z]+) \*/", src)
        if not m or m.group(1) != "sig-" + name:
            sys.exit("sig/%s.css must start with /*! id: sig-%s */" % (name, name))
        body = expand(src, m.group(1))
        if PH.search(body):
            sys.exit("unexpanded placeholder in " + name)
        out.append(body)
    css = "\n".join(out)
    # light minify: comments and runs of whitespace (keep /*! */ headers)
    css = re.sub(r"/\*(?!!).*?\*/", "", css, flags=re.S)
    css = re.sub(r"[ \t]*\n[ \t\n]*", "\n", css)
    css = re.sub(r"[ \t]{2,}", " ", css)
    return "/* VPEX Signature themes. Generated by sig/build.py from sig/*.css; edit those, not this. */\n" + css.strip() + "\n"


if __name__ == "__main__":
    css = build()
    dest = ROOT / "sig.css"
    if "--check" in sys.argv:
        sys.exit(0 if dest.exists() and dest.read_text() == css else "sig.css is out of date: run python3 sig/build.py")
    dest.write_text(css)
    print("sig.css: %d bytes" % len(css.encode()))
